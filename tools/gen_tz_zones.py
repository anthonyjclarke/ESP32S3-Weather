# Regenerates include/tz_zones.h: IANA timezone name -> POSIX TZ string, served
# to the WebUI at /tz.json so users pick "Australia/Sydney" instead of typing
# "AEST-10AEDT,M10.1.0,M4.1.0/3".
#
# Source: nayarsystems/posix_tz_db (MIT), built from IANA tzdata. Re-run after
# a tzdata change; bump COMMIT to the upstream commit you want.
#
#   python3 tools/gen_tz_zones.py
import json
import pathlib
import subprocess

COMMIT = "93447c0ddac304ca6672a5fd905261c7e8905159"
URL = f"https://raw.githubusercontent.com/nayarsystems/posix_tz_db/{COMMIT}/zones.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "include" / "tz_zones.h"

# curl rather than urllib: PlatformIO's bundled Python has no CA store.
zones = json.loads(subprocess.run(["curl", "-fsSL", URL], check=True, capture_output=True).stdout)
body = json.dumps(dict(sorted(zones.items())), separators=(",", ":"))
assert ")TZ\"" not in body
OUT.write_text(
    "#pragma once\n"
    "// Generated by tools/gen_tz_zones.py - do not edit.\n"
    f"// IANA name -> POSIX TZ, from nayarsystems/posix_tz_db@{COMMIT[:7]} (MIT).\n"
    f"const char kTzZonesJson[] PROGMEM = R\"TZ({body})TZ\";\n"
)
print(f"{len(zones)} zones, {len(body)} bytes -> {OUT}")
